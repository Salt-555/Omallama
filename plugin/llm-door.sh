#!/usr/bin/env bash
# Enable/disable the :6969 rate-limit door.
#
# The omallama backends now publish/bind 127.0.0.1:6969 ONLY (serve-basalt /
# serve-sglang / serve-gufo use -p 127.0.0.1:..., every llama.cpp launcher
# binds --host 127.0.0.1), which frees the box's EXTERNAL addresses on :6969
# for nginx. When enabled, this door serves the SAME per-IP lane limits as
# :8191 — external clients keep their endpoint and gain the limits. Loopback
# :6969 remains the backends' own port: cardmode's gates, the widget and
# local Hermes talk to it directly and are never limited.
#
# enable    write the server block (listening on every global IPv4 address
#           the box has right now) into llm-door-6969.conf, nginx -t, HUP.
#           Refuses while a backend is still published wide (docker-proxy or
#           a 0.0.0.0 llama-server holds external :6969) — restart the
#           current backend first; it picks up the loopback publish, then run
#           enable again.
# disable   empty the include and HUP — external :6969 goes quiet (clients
#           get connection-refused until enabled again).
# status    report door state and the addresses it would use.
set -euo pipefail

CONF_DIR="$HOME/.config/cardmode"
DOOR="$CONF_DIR/llm-door-6969.conf"
NGINX_CONF="$CONF_DIR/nginx.conf"
PREFIX="$HOME/.local/state/cardmode"
PIDFILE="$PREFIX/run/nginx.pid"

EMPTY_NOTE="# EMPTY on purpose: the :6969 door is DISABLED. llm-door.sh enable writes the
# server block here (listening on the box's external addresses at :6969) and
# HUPs this nginx; disable empties the file again. Empty until then keeps the
# reload path valid while backends still publish 0.0.0.0:6969."

discover_ips() {
  # Real uplinks only: every global IPv4 address EXCEPT docker bridges
  # (172.16/12) — the bridges are reachability junk and any container on them
  # would otherwise get a door into the LLM.
  ip -4 -o addr show scope global 2>/dev/null \
    | awk '{split($4,a,"/"); if (a[1] !~ /^172\.(1[6-9]|2[0-9]|3[01])\./) print a[1]}' \
    | sort -u
}

bind_test() {
  # Exit 0 only if WE can bind this address at :6969 — i.e. no backend is
  # still published wide (docker-proxy holds 0.0.0.0:6969 as root, which no
  # ss -p as a user can see; a real bind attempt is the only honest check).
  python3 - "$1" <<'EOF'
import socket, sys
s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 0)
try:
    s.bind((sys.argv[1], 6969))
except OSError:
    sys.exit(1)
finally:
    s.close()
EOF
}

hup() {
  if [[ -f "$PIDFILE" ]] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; then
    /usr/sbin/nginx -t -p "$PREFIX" -c "$NGINX_CONF" >/dev/null
    kill -HUP "$(cat "$PIDFILE")"
  else
    echo "cardmode nginx not running; door file written, takes effect on start" >&2
  fi
}

write_door() {
  local tmp="$DOOR.tmp.$$"
  {
    echo "# generated by llm-door.sh enable $(date +%F' '%T) — regenerate by running enable again."
    echo "# Primary: the per-client queueing gateway. Backup: the engine direct —"
    echo "# if the gateway dies the door degrades to unqueued rather than offline."
    echo "upstream llmgw {"
    echo "    server 127.0.0.1:6962 max_fails=2 fail_timeout=5s;"
    echo "    server 127.0.0.1:6969 backup;"
    echo "}"
    echo "server {"
    while read -r ip; do
      echo "    listen $ip:6969;"
    done <<< "$1"
    echo "    server_name _;"
    echo "    client_body_temp_path client_body;"
    echo "    access_log logs/llm-access.log;"
    echo "    # Prompts and base64 images are multi-MB; nginx's 1 MB default 413s them."
    echo "    client_max_body_size 0;"
    echo "    # Status reads bypass the gateway's lanes: dashboards must never"
    echo "    # queue behind generation."
    for p in "= /health" "= /v1/models" "= /models" "= /metrics" "= /props" "= /v1/props"; do
      echo "    location $p {"
      echo "        proxy_pass http://llmgw;"
      echo "        proxy_http_version 1.1;"
      echo "        # Basalt's DNS-rebinding check 403s hostname Hosts (e.g. 'llmgw'"
      echo "        # on the engine-direct fallback); pin a numeric Host everywhere."
      echo "        proxy_set_header Host \$host;"
      echo "    }"
    done
    echo "    location / {"
    echo "        # If gateway AND engine are both unreachable, the turn still gets"
    echo "        # a named wait instead of a bare 502."
    echo "        error_page 502 504 = @llm_unavailable;"
    echo "        proxy_pass http://llmgw;"
    echo "        proxy_http_version 1.1;"
    echo "        proxy_set_header Host \$host;"
    echo "        # Client identity for the queue: overwritten, never appended,"
    echo "        # so a client cannot forge another client's lanes."
    echo "        proxy_set_header X-Forwarded-For \$remote_addr;"
    echo "        proxy_read_timeout 86400s;"
    echo "        proxy_send_timeout 86400s;"
    echo "        proxy_buffering off;"
    echo "    }"
    echo "    location @llm_unavailable {"
    echo "        add_header Retry-After 30 always;"
    echo "        default_type text/plain;"
    echo "        return 503 \"model reloading — the turn will resume on retry\\n\";"
    echo "    }"
    echo "}"
  } > "$tmp"
  mv "$tmp" "$DOOR"
}

case "${1:-}" in
  # Best-effort re-render of the door at proxy start (cardmode-proxy
  # ExecStartPre). NEVER fails the unit: a missing/unreachable IP renders a
  # door without that address, a disabled door renders nothing — the proxy
  # must come up either way. This is what keeps a DHCP address change from
  # turning into a proxy outage: the listen lines are re-derived from the
  # live interfaces at every start, not frozen from the day enable ran.
  render)
    if ! grep -qE '^[[:space:]]*listen ' "$DOOR" 2>/dev/null; then
      exit 0  # door disabled; nothing to render
    fi
    ips=$(discover_ips 2>/dev/null || true)
    [[ -n "$ips" ]] || { echo "llm-door render: no addresses found; leaving door file untouched" >&2; exit 0; }
    if [[ "$(grep -cE '^[[:space:]]*listen ' "$DOOR" 2>/dev/null || echo 0)" -gt 0 ]] \
       && [[ "$(grep -oE 'listen [0-9.]+' "$DOOR" | awk '{print $2}' | sort | tr '\n' ' ')" \
          == "$(echo "$ips" | sort | tr '\n' ' ')" ]]; then
      exit 0  # unchanged; don't touch the file (no pointless HUP bait)
    fi
    write_door "$ips" 2>/dev/null || true
    echo "llm-door render: listen set now $(echo "$ips" | tr '\n' ' ')" >&2
    exit 0
    ;;
  enable)
    ips=$(discover_ips)
    [[ -n "$ips" ]] || { echo "no global IPv4 addresses found" >&2; exit 1; }
    # Idempotent: once enabled, THIS nginx holds the addresses, so a bind test
    # would refuse our own regenerate. If the listen set already matches, just
    # re-render and reload.
    if [[ "$(grep -cE '^[[:space:]]*listen ' "$DOOR" 2>/dev/null || echo 0)" -gt 0 ]]; then
      write_door "$ips"
      hup && echo "door re-rendered on: $(echo "$ips" | tr '\n' ' ')"
      exit 0
    fi
    for ip in $ips; do
      if ! bind_test "$ip"; then
        echo "refusing: $ip:6969 is held by something else — the current backend is still" >&2
        echo "published wide (docker-proxy) or a llama.cpp server binds 0.0.0.0." >&2
        echo "Restart the serving backend; the edited launchers now publish loopback-only." >&2
        echo "Then run enable again." >&2
        exit 1
      fi
    done
    cp -a "$DOOR" "$DOOR.prev" 2>/dev/null || true
    write_door "$ips"
    if hup; then
      echo "door enabled on: $ips"
    else
      # Restore the previous door, or empty it on a first enable — a broken
      # door file must never wait for the next proxy start.
      if [[ -f "$DOOR.prev" ]]; then mv "$DOOR.prev" "$DOOR"; else echo "$EMPTY_NOTE" > "$DOOR"; fi
      echo "nginx -t rejected the door config; previous state kept" >&2
      exit 1
    fi
    ;;
  disable)
    echo "$EMPTY_NOTE" > "$DOOR"
    hup && echo "door disabled — external :6969 no longer listens"
    ;;
  status)
    if grep -qE '^[[:space:]]*listen ' "$DOOR" 2>/dev/null; then
      echo "enabled: $(grep -oE 'listen [^;]+' "$DOOR" | sed 's/listen //')"
    else
      echo "disabled (would use: $(discover_ips | tr '\n' ' '))"
    fi
    ;;
  *)
    echo "usage: llm-door.sh {enable|disable|status}" >&2
    exit 1
    ;;
esac
